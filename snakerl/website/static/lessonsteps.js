/*
This JavaScript for parameters.html was fully generated by Claude Code.

Shows a lesson page one <section class="lesson-step"> at a time.

Expects on the page:
    #lessonSteps   container holding the .lesson-step sections
    #stepNav       previous / counter / next controls (starts hidden)
    #continueBtn   (optional) link to the next page, shown only on the last step

The current step's id is kept in the URL (e.g. /parameters#bellman), so a
reload or the browser's back/forward buttons return to the same step.
Sidebar links to a step on this page (.site-nav-sublink[data-step]) jump
straight to it, and the one for the step showing is highlighted.
If this script fails to run, every section stays visible as one long page.
*/

(function () {
    const container = document.getElementById("lessonSteps");
    const steps = Array.from(container.querySelectorAll(".lesson-step"));
    const nav = document.getElementById("stepNav");
    const prevBtn = document.getElementById("prevStep");
    const nextBtn = document.getElementById("nextStep");
    const counter = document.getElementById("stepCounter");
    const continueBtn = document.getElementById("continueBtn");
    const sidebarLinks = Array.from(document.querySelectorAll(".site-nav-sublink[data-step]"))
        .filter(link => link.pathname === location.pathname);
    let current = 0;

    // Index of the step named in the URL hash, or the first step
    function indexFromHash() {
        const id = decodeURIComponent(location.hash.slice(1));
        const i = steps.findIndex(step => step.id === id);
        return i === -1 ? 0 : i;
    }

    // Show step i and hide the rest; update the controls to match
    function show(i) {
        current = i;
        steps.forEach((step, j) => step.classList.toggle("active", j === i));
        counter.textContent = (i + 1) + " / " + steps.length;
        prevBtn.disabled = i === 0;
        nextBtn.disabled = i === steps.length - 1;
        if (continueBtn) {
            continueBtn.hidden = i !== steps.length - 1;
        }
        // Highlight this step in the navigation sidebar
        sidebarLinks.forEach(link => {
            const isCurrent = link.dataset.step === steps[i].id;
            link.classList.toggle("current", isCurrent);
            if (isCurrent) {
                link.setAttribute("aria-current", "step");
            } else {
                link.removeAttribute("aria-current");
            }
        });
    }

    // Move to step i: show it, record it in history, and scroll to its top
    function go(i) {
        show(i);
        history.pushState(null, "", "#" + steps[i].id);
        // Scroll up if the top of the lesson is hidden under the sticky header
        const header = document.querySelector(".site-header");
        const headerHeight = header ? header.offsetHeight : 0;
        if (container.getBoundingClientRect().top < headerHeight) {
            container.scrollIntoView({ behavior: "smooth", block: "start" });
        }
    }

    prevBtn.addEventListener("click", () => go(current - 1));
    nextBtn.addEventListener("click", () => go(current + 1));

    // Sidebar links to a step on this page: show that step instead of reloading
    sidebarLinks.forEach(link => {
        link.addEventListener("click", (event) => {
            const i = steps.findIndex(step => step.id === link.dataset.step);
            if (i !== -1) {
                event.preventDefault();
                if (i !== current) {
                    go(i);
                }
            }
        });
    });

    // Browser back/forward between steps
    window.addEventListener("popstate", () => show(indexFromHash()));

    // Switch the page into one-step-at-a-time mode
    container.classList.add("paged");
    nav.hidden = false;
    // With a step in the URL, the browser scrolls to that section on load;
    // scroll-margin-top in base.css keeps its heading clear of the header
    show(indexFromHash());
})();
